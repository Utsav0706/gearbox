"""Compare routers on the held-out test split (M5): reports/routers.md + .json.

    py -m gearbox.routers.compare                      # all routers (v2 costs ~GBP 0.02)
    py -m gearbox.routers.compare --routers v1-rules v3-embed   # free ones only

Routing metrics (the M5 question, "does it pick the label?"):
- accuracy and the confusion matrix against the M4 labels;
- under-routing (picked a smaller tier than the label: a worse answer), reported
  separately from over-routing (a bigger tier than needed: only wasted money);
- the time the routing decision itself adds (p50/p95).

Outcome preview from the stored M3 answers and M4 judgments (no new model calls): if
every test prompt were answered by the tier the router picked, what share of answers
would pass the judge, and what would it cost at list price? Always-S/M/L and the oracle
(the label itself) are included for scale. M8 turns this into the real end-to-end eval.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import statistics
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from gearbox.config import TIERS, Tier, get_config
from gearbox.data.answer import BATCH_DISCOUNT, load_answers
from gearbox.data.judge import PASS_SCORE, load_judgments
from gearbox.log import setup_logging
from gearbox.routers import Route, available, create_router


@dataclass
class Prediction:
    id: str
    router: str
    tier: Tier
    reason: str
    latency_ms: float
    cost_gbp: float  # cost of the routing decision itself (v2's classifier call)


def confusion(truth: list[Tier], pred: list[Tier]) -> list[list[int]]:
    """rows = label (S, M, L), columns = router's pick (S, M, L)."""
    m = [[0] * 3 for _ in TIERS]
    for t, p in zip(truth, pred, strict=True):
        m[TIERS.index(t)][TIERS.index(p)] += 1
    return m


def routing_metrics(truth: list[Tier], preds: list[Prediction]) -> dict[str, Any]:
    picked = [p.tier for p in preds]
    rank = TIERS.index
    lat = sorted(p.latency_ms for p in preds)
    return {
        "accuracy": sum(t == p for t, p in zip(truth, picked, strict=True)) / len(truth),
        "under_rate": sum(rank(p) < rank(t) for t, p in zip(truth, picked, strict=True))
        / len(truth),
        "over_rate": sum(rank(p) > rank(t) for t, p in zip(truth, picked, strict=True))
        / len(truth),
        "confusion": confusion(truth, picked),
        "latency_p50_ms": statistics.median(lat),
        "latency_p95_ms": lat[min(len(lat) - 1, int(0.95 * len(lat)))],
        "routing_cost_gbp": sum(p.cost_gbp for p in preds),
        "picks": {t: picked.count(t) for t in TIERS},
    }


def outcome(
    ids: list[str],
    picks: list[Tier],
    scores: dict[tuple[str, str], int],
    costs: dict[tuple[str, str], float],
) -> dict[str, float]:
    """If each prompt were answered by the picked tier: pass rate, mean score, cost."""
    keys = list(zip(ids, picks, strict=True))
    return {
        "pass_rate": sum(scores[k] >= PASS_SCORE for k in keys) / len(keys),
        "mean_score": sum(scores[k] for k in keys) / len(keys),
        "answer_cost_gbp": sum(costs[k] for k in keys),
    }


async def run_router(name: str, ids: list[str], texts: list[str]) -> list[Prediction]:
    router = create_router(name)
    preds = []
    for pid, text in zip(ids, texts, strict=True):
        start = time.perf_counter()
        route: Route = await router.route(text)
        ms = (time.perf_counter() - start) * 1000
        cost = float(getattr(router, "last_cost_gbp", 0.0))
        preds.append(Prediction(pid, name, route.tier, route.reason, round(ms, 2), cost))
    return preds


def _pct(v: float) -> str:
    return f"{100 * v:.1f}%"


def render(report: dict[str, Any]) -> str:
    n, mix = report["test_prompts"], report["label_mix"]
    lines = [
        "# Router comparison (M5)",
        "",
        f"Test split: {n} held-out prompts, labels S {mix['S']} / M {mix['M']} / L {mix['L']}.",
        "Generated by `py -m gearbox.routers.compare`; numbers in `reports/routers.json`.",
        "",
        "## Routing",
        "",
        "| router | accuracy | under-routed | over-routed | picks S/M/L | added latency p50 / p95 "
        "| routing cost |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in report["routers"].items():
        m = r["routing"]
        lines.append(
            f"| {name} | {_pct(m['accuracy'])} | {_pct(m['under_rate'])} | "
            f"{_pct(m['over_rate'])} | {m['picks']['S']}/{m['picks']['M']}/{m['picks']['L']} | "
            f"{m['latency_p50_ms']:.0f} / {m['latency_p95_ms']:.0f} ms | "
            f"GBP {m['routing_cost_gbp']:.4f} |"
        )
    lines += ["", "Confusion matrices (rows = label, columns = router's pick):", ""]
    for name, r in report["routers"].items():
        c = r["routing"]["confusion"]
        lines += [f"**{name}**", "", "| label \\ pick | S | M | L |", "|---|---|---|---|"]
        lines += [f"| {t} | {c[i][0]} | {c[i][1]} | {c[i][2]} |" for i, t in enumerate(TIERS)]
        lines.append("")
    lines += [
        "## Outcome preview (stored answers, no new calls)",
        "",
        "If each test prompt were answered by the tier picked: share of answers the judge",
        "passes, mean judge score, and answer cost at list price. L = always Sonnet.",
        "",
        "| strategy | pass rate | mean score | answer cost | cost vs always-L |",
        "|---|---|---|---|---|",
    ]
    base = report["baselines"]["always-L"]["answer_cost_gbp"]
    rows = {**report["baselines"], **{k: v["outcome"] for k, v in report["routers"].items()}}
    for name, o in rows.items():
        lines.append(
            f"| {name} | {_pct(o['pass_rate'])} | {o['mean_score']:.2f} | "
            f"GBP {o['answer_cost_gbp']:.4f} | {_pct(o['answer_cost_gbp'] / base)} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="py -m gearbox.routers.compare",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--data", type=Path, default=Path("data/v1"))
    parser.add_argument("--routers", nargs="+", default=None)
    parser.add_argument("--out", type=Path, default=Path("reports"))
    args = parser.parse_args(argv)
    setup_logging("WARNING")
    get_config()

    split = json.loads((args.data / "split.json").read_text(encoding="utf-8"))
    ids: list[str] = split["test"]
    prompts = {}
    with (args.data / "prompts.jsonl").open(encoding="utf-8") as f:
        for line in f:
            row = json.loads(line)
            prompts[row["id"]] = row["prompt"]
    labels = {}
    with (args.data / "labels.jsonl").open(encoding="utf-8") as f:
        for line in f:
            row = json.loads(line)
            labels[row["id"]] = row["label"]
    truth: list[Tier] = [labels[i] for i in ids]
    scores = {(j.id, j.tier): j.score for j in load_judgments(args.data)}
    # The live service pays list price; batch answers were billed at half of it.
    costs = {
        (a.id, a.tier): a.cost_gbp / (BATCH_DISCOUNT if a.via == "batch" else 1)
        for a in load_answers(args.data)
    }

    report: dict[str, Any] = {
        "test_prompts": len(ids),
        "label_mix": {t: truth.count(t) for t in TIERS},
        "baselines": {f"always-{t}": outcome(ids, [t] * len(ids), scores, costs) for t in TIERS},
        "routers": {},
    }
    report["baselines"]["oracle (label)"] = outcome(ids, truth, scores, costs)

    all_preds: list[Prediction] = []
    for name in args.routers or available():
        print(f"running {name} on {len(ids)} prompts...")
        preds = asyncio.run(run_router(name, ids, [prompts[i] for i in ids]))
        all_preds += preds
        report["routers"][name] = {
            "routing": routing_metrics(truth, preds),
            "outcome": outcome(ids, [p.tier for p in preds], scores, costs),
        }

    args.out.mkdir(exist_ok=True)
    (args.out / "routers.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (args.out / "router_predictions.jsonl").write_text(
        "".join(json.dumps(p.__dict__) + "\n" for p in all_preds), encoding="utf-8", newline="\n"
    )
    md = render(report)
    (args.out / "routers.md").write_text(md, encoding="utf-8", newline="\n")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
