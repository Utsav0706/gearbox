"""py -m gearbox.eval [offline]        -> reports/eval.md, eval.json, cost_quality.svg (free)
py -m gearbox.eval live [--yes]     -> also checks the running API end to end (paid)

offline replays the stored answers and judge scores (data/v2) for every strategy and
the router predictions in reports/router_predictions.jsonl (refresh those with
py -m gearbox.routers.compare). Same inputs, same numbers, every run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from gearbox.config import get_config
from gearbox.eval.chart import cost_quality_svg
from gearbox.eval.offline import evaluate, headline, load_dataset, load_strategies
from gearbox.log import setup_logging


def render(results: dict[str, Any], router: str, n: int, live: dict[str, Any] | None) -> str:
    lines = [
        "# Eval: cost vs quality",
        "",
        f"> **{headline(results, router, n)}**",
        "",
        "Generated by `py -m gearbox.eval` from stored answers and judge scores "
        "(`data/v2`, test split), so it costs nothing and gives the same numbers every run.",
        "Quality = mean judge score (1-5) as a % of always-L's; cost = answers at list "
        "price plus the cost of routing itself, as a % of always-L. Intervals are 95% "
        "bootstrap intervals over the test prompts.",
        "",
        "![Cost vs quality](cost_quality.svg)",
        "",
        "| strategy | quality | 95% CI | pass rate | cost vs L | saved | 95% CI | per 1k requests "
        "| picks S/M/L | routing p50 / p95 |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        q, s = r["quality_pct_ci95"], r["saved_pct_ci95"]
        p = r["picks"]
        lines.append(
            f"| {name} | {r['quality_pct']:.1f}% | {q[0]:.0f}-{q[1]:.0f}% | "
            f"{100 * r['pass_rate']:.1f}% | {r['cost_pct']:.1f}% | {r['saved_pct']:.1f}% | "
            f"{s[0]:.0f}-{s[1]:.0f}% | GBP {r['cost_per_1k_requests_gbp']:.3f} | "
            f"{p['S']}/{p['M']}/{p['L']} | {r['route_p50_ms']:.0f} / {r['route_p95_ms']:.0f} ms |"
        )
    m, v = results["always-M"], results[router]
    lines += [
        "",
        "## Reading it",
        "",
        f"- The configured router ({router}) lands next to always-M (Claude Haiku 5.5): "
        f"{v['quality_pct']:.1f}% vs {m['quality_pct']:.1f}% quality at "
        f"{v['cost_pct']:.1f}% vs {m['cost_pct']:.1f}% of the cost. On these prompts the "
        "medium tier is good enough so often that a router mostly learns to pick it.",
        f"- The oracle (perfect knowledge of the cheapest passing tier) reaches "
        f"{results['oracle']['quality_pct']:.1f}% at {results['oracle']['cost_pct']:.1f}%: "
        "the room left for a better router. Which prompts only the large tier answers "
        "well proved hard to predict from the prompt alone (see `routers.md`).",
        "- v2-llm pays for a classifier call on every request (included in its cost) and "
        "adds about two seconds before the answer starts.",
    ]
    if live:
        lines += [
            "",
            "## Live check through the API",
            "",
            f"{live['prompts']} test prompts sent to the running service "
            f"(`POST /v1/chat/completions`, model auto), answers judged the same way:",
            "",
            "| | quality | pass rate | answer cost | saved vs always-L | picks S/M/L | "
            "latency p50 / p95 |",
            "|---|---|---|---|---|---|---|",
            f"| live | {live['quality_pct']:.1f}% | {100 * live['pass_rate']:.1f}% | "
            f"GBP {live['answer_cost_gbp']:.4f} | {live['saved_pct']:.1f}% | "
            f"{live['picks']['S']}/{live['picks']['M']}/{live['picks']['L']} | "
            f"{live['latency_p50_ms'] / 1000:.1f} / {live['latency_p95_ms'] / 1000:.1f} s |",
            f"| offline replay | {v['quality_pct']:.1f}% | {100 * v['pass_rate']:.1f}% | "
            f"GBP {v['cost_gbp']:.4f} | {v['saved_pct']:.1f}% | "
            f"{v['picks']['S']}/{v['picks']['M']}/{v['picks']['L']} | |",
            "",
            f"Fresh answers differ from the stored ones (models are not deterministic), so "
            f"small differences are expected. Judging cost GBP {live['judge_cost_gbp']:.3f}.",
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="py -m gearbox.eval",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("mode", nargs="?", choices=["offline", "live"], default="offline")
    parser.add_argument("--data", type=Path, default=Path("data/v2"))
    parser.add_argument(
        "--predictions", type=Path, default=Path("reports/router_predictions.jsonl")
    )
    parser.add_argument("--out", type=Path, default=Path("reports"))
    parser.add_argument("--base-url", default="http://127.0.0.1:8002")
    parser.add_argument("--cap-gbp", type=float, default=0.60)
    parser.add_argument("--yes", action="store_true", help="live: actually send (costs money)")
    args = parser.parse_args(argv)
    setup_logging("WARNING")
    config = get_config()
    router = config.routing.router

    ds = load_dataset(args.data)
    results = evaluate(ds, load_strategies(ds, args.predictions))
    args.out.mkdir(exist_ok=True)
    live_path = args.out / "eval_live.json"
    live = json.loads(live_path.read_text(encoding="utf-8")) if live_path.exists() else None

    if args.mode == "live":
        from gearbox.eval import live as live_eval

        estimate = live_eval.estimate_gbp(len(ds.ids), results, router, args.data)
        print(
            f"live eval: {len(ds.ids)} prompts via {args.base_url}, "
            f"estimate GBP {estimate:.2f} (cap {args.cap_gbp:.2f})"
        )
        if estimate > args.cap_gbp:
            print("REFUSED: estimate is over the cap")
            return 1
        if not args.yes:
            print("dry run: add --yes to send it")
            return 0
        run = live_eval.run(args.base_url, args.data, config, ds.ids, args.out)
        live = live_eval.summarise(run["answers"], run["judged"], results)
        live_path.write_text(json.dumps(live, indent=2) + "\n", encoding="utf-8", newline="\n")

    (args.out / "eval.json").write_text(
        json.dumps({"router": router, "test_prompts": len(ds.ids), "results": results}, indent=2)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    (args.out / "cost_quality.svg").write_text(
        cost_quality_svg(results, len(ds.ids)), encoding="utf-8", newline="\n"
    )
    (args.out / "eval.md").write_text(
        render(results, router, len(ds.ids), live), encoding="utf-8", newline="\n"
    )
    print(headline(results, router, len(ds.ids)))
    print(f"wrote {args.out / 'eval.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
