"""The live eval, run by Dyno (the agent-eval harness): `make eval-live`.

    py -m gearbox.eval.dyno cases --n 30            # the case file Dyno reads
    py -m gearbox.eval.dyno run --n 30              # estimate only
    py -m gearbox.eval.dyno run --n 30 --yes        # PAID: answers + Dyno's judges

Test prompts go through the running API (port 8002) as Dyno's `gearbox` agent; Dyno's
calibrated judges score the answers (task_rubric where a gold answer exists, quality on
all). Gearbox then reports in its own terms:

- Dyno's pass rates;
- the tier mix and cost of the run, from Gearbox's own request log (Dyno's cost figure
  must match it);
- cost saved against always-L, using the stored cost of the large tier's answer to the
  same prompts (no Sonnet run needed);
- how Dyno's quality judge agrees with Gearbox's own stored judge on the same prompts
  and picks. They are different judges with different rubrics, and Dyno judges a fresh
  answer while the stored judge saw an earlier one, so agreement, not identity, is
  what to expect.

Dyno runs from its own environment (DYNO_BIN): Gearbox needs the Anthropic SDK 1.x,
Dyno 2.x, so they can't share one. The two exchange files only: a case file in Dyno's
YAML format, and Dyno's JSON report. The free offline replay (`make eval`) stays:
Dyno can't re-price stored answers.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import re
import subprocess
import sys
import time
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from gearbox.config import TIERS, get_config, get_secrets
from gearbox.data.judge import PASS_SCORE
from gearbox.eval.offline import load_dataset

DATA = Path("data/v2")
SUITE = Path("eval/dyno_suite.yaml")
PREDICTIONS = Path("reports/router_predictions.jsonl")
DEFAULT_DYNO_BIN = Path(
    "../dyno/.venv/Scripts/dyno.exe" if os.name == "nt" else "../dyno/.venv/bin/dyno"
)
# Per prompt: an answer (mostly Haiku) + Dyno's task_rubric and quality judges (Haiku).
EST_ANSWER_GBP = 0.0007
EST_JUDGES_GBP = 0.0033
DEFAULT_CAP_GBP = 0.25


class DynoError(RuntimeError):
    pass


# --- cases ------------------------------------------------------------------------------


def sample_ids(data_dir: Path, n: int, seed: int = 20261119) -> list[str]:
    """n test prompts, stratified by task type (round-robin over shuffled groups)."""
    prompts = _prompts(data_dir)
    test = json.loads((data_dir / "split.json").read_text(encoding="utf-8"))["test"]
    groups: dict[str, list[str]] = defaultdict(list)
    for pid in sorted(test):
        groups[prompts[pid]["task_type"]].append(pid)
    rng = random.Random(seed)
    for ids in groups.values():
        rng.shuffle(ids)
    picked: list[str] = []
    while len(picked) < min(n, len(test)):
        for task in sorted(groups):
            if groups[task] and len(picked) < n:
                picked.append(groups[task].pop())
    return picked


def _prompts(data_dir: Path) -> dict[str, dict[str, Any]]:
    with (data_dir / "prompts.jsonl").open(encoding="utf-8") as f:
        return {row["id"]: row for row in map(json.loads, f)}


def build_cases(data_dir: Path, ids: list[str]) -> list[dict[str, Any]]:
    """Dyno cases. A gold reference becomes `expected` (task_rubric's key point), except
    for code: its gold answer is a full program, which a judge can't match key points
    against (it made task_rubric undercount), so code is judged on quality alone."""
    prompts = _prompts(data_dir)
    cases = []
    for pid in ids:
        row = prompts[pid]
        case: dict[str, Any] = {
            "id": pid,
            "input": row["prompt"],
            "tags": [row["task_type"], row["source"], row["difficulty"]],
        }
        if (
            row.get("reference_kind") == "gold"
            and row.get("reference")
            and row["task_type"] != "coding"
        ):
            case["expected"] = str(row["reference"])
        cases.append(case)
    return cases


def write_cases(cases: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by `py -m gearbox.eval.dyno cases` from data/v2's test split.\n"
    body = yaml.safe_dump({"cases": cases}, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(header + body, encoding="utf-8", newline="\n")


# --- running Dyno ------------------------------------------------------------------------


def estimate_gbp(n: int) -> float:
    return n * (EST_ANSWER_GBP + EST_JUDGES_GBP)


def run_dyno(dyno_bin: Path, cases_file: Path, db_file: Path, cap_gbp: float) -> str:
    """`dyno run`; returns Dyno's run id."""
    if not dyno_bin.exists():
        raise DynoError(f"Dyno not found at {dyno_bin} (set DYNO_BIN to Dyno's `dyno` command)")
    secrets = get_secrets()
    if secrets.anthropic_api_key is None:
        raise DynoError("ANTHROPIC_API_KEY is not set (Dyno's judges need it)")
    env = {
        **os.environ,
        "DATABASE_URL": f"sqlite:///{db_file.resolve().as_posix()}",
        "GEARBOX_URL": secrets.gearbox_url,
        "ANTHROPIC_API_KEY": secrets.anthropic_api_key.get_secret_value(),
        "JUDGE_BUDGET_GBP": f"{cap_gbp:.4f}",
        "PYTHONIOENCODING": "utf-8",
    }
    result = subprocess.run(
        [str(dyno_bin), "run", str(SUITE), "--cases", str(cases_file)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=env,
    )
    match = re.search(r"^run (\w+):", result.stdout, re.MULTILINE)
    if result.returncode != 0 or not match:
        raise DynoError(f"dyno run failed: {(result.stderr or result.stdout)[-800:]}")
    return match.group(1)


def dyno_report(dyno_bin: Path, run_id: str, db_file: Path) -> dict[str, Any]:
    result = subprocess.run(
        [str(dyno_bin), "report", run_id, "--format", "json"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env={**os.environ, "DATABASE_URL": f"sqlite:///{db_file.resolve().as_posix()}"},
    )
    if result.returncode != 0:
        raise DynoError(f"dyno report failed: {result.stderr[-400:]}")
    return json.loads(result.stdout)


def request_log_window(start: datetime, end: datetime) -> list[dict[str, Any]]:
    """Gearbox's own request log rows written while Dyno ran."""
    from sqlalchemy import select

    from gearbox.service.db import RequestLog, make_engine, make_sessions

    sessions = make_sessions(make_engine(get_secrets().database_url))
    with sessions() as s:
        rows = s.scalars(
            select(RequestLog).where(RequestLog.created_at >= start, RequestLog.created_at <= end)
        ).all()
    return [
        {"tier": r.tier, "cost_gbp": r.cost_gbp, "status": r.status, "router": r.router}
        for r in rows
    ]


# --- the report ------------------------------------------------------------------------------


def summarise(
    report: dict[str, Any],
    ids: list[str],
    log_rows: list[dict[str, Any]],
    data_dir: Path,
    picks: dict[str, str],
) -> dict[str, Any]:
    """Dyno's results in Gearbox's terms (pure: everything it needs is passed in)."""
    ds = load_dataset(data_dir)
    scorers = {s["scorer"]: s for s in report["scorers"]}
    quality_failed = {f["case_id"] for f in report["failures"] if f["scorer"] == "quality"}

    agreement: Counter[str] = Counter()
    disagreements = []
    for pid in ids:
        tier = picks.get(pid)
        stored = ds.scores.get((pid, tier)) if tier else None
        if stored is None:
            agreement["no stored score"] += 1
            continue
        dyno_pass = pid not in quality_failed
        stored_pass = stored >= PASS_SCORE
        if dyno_pass == stored_pass:
            agreement["both pass" if dyno_pass else "both fail"] += 1
        else:
            agreement["Dyno pass, stored fail" if dyno_pass else "Dyno fail, stored pass"] += 1
            disagreements.append(
                {"id": pid, "tier": tier, "stored_score": stored, "dyno_pass": dyno_pass}
            )

    live_cost = sum(r["cost_gbp"] for r in log_rows)
    always_l = sum(ds.costs.get((pid, "L"), 0.0) for pid in ids)
    judged = sum(agreement[k] for k in agreement if k != "no stored score")
    agree = agreement["both pass"] + agreement["both fail"]
    return {
        "prompts": len(ids),
        "dyno_run": report["run_id"],
        "pass_rate": {name: s["pass_rate"] for name, s in scorers.items()},
        "scored": {name: s["scored"] for name, s in scorers.items()},
        "tiers": dict(Counter(r["tier"] for r in log_rows if r["tier"])),
        "errors": sum(r["status"] == "error" for r in log_rows),
        "cost_gbp": round(live_cost, 6),
        "dyno_cost_gbp": report.get("cost_gbp"),
        "judge_cost_gbp": report.get("judge_cost_gbp"),
        "always_l_cost_gbp": round(always_l, 6),
        "saved_vs_always_l": round(1 - live_cost / always_l, 4) if always_l else None,
        "agreement": dict(agreement),
        "agreement_rate": round(agree / judged, 4) if judged else None,
        "disagreements": disagreements,
    }


def render(s: dict[str, Any]) -> str:
    def pct(v: float | None) -> str:
        return "-" if v is None else f"{100 * v:.1f}%"

    lines = [
        "# Live eval through Dyno",
        "",
        f"Generated by `py -m gearbox.eval.dyno run`: {s['prompts']} test prompts through the "
        f"running API, judged by Dyno (run `{s['dyno_run']}`).",
        "",
        "| | |",
        "|---|---|",
    ]
    for name, rate in s["pass_rate"].items():
        lines.append(f"| Dyno `{name}` pass rate | {pct(rate)} ({s['scored'][name]} scored) |")
    tiers = "/".join(str(s["tiers"].get(t, 0)) for t in TIERS)
    lines += [
        f"| Tiers S/M/L (request log) | {tiers} |",
        f"| Errors | {s['errors']} |",
        f"| Answer cost (request log) | GBP {s['cost_gbp']:.4f} "
        f"(Dyno counted GBP {s['dyno_cost_gbp'] or 0:.4f}) |",
        f"| Same prompts, always-L (stored) | GBP {s['always_l_cost_gbp']:.4f} |",
        f"| Saved vs always-L | {pct(s['saved_vs_always_l'])} |",
        f"| Dyno's judging cost | GBP {s['judge_cost_gbp'] or 0:.4f} |",
        "",
        "## Dyno's quality judge vs Gearbox's stored judge",
        "",
        "Same prompts, same tier (the router's stored pick), different judges and answers:",
        "",
        "| | Prompts |",
        "|---|---|",
    ]
    for key, count in sorted(s["agreement"].items()):
        lines.append(f"| {key} | {count} |")
    lines += ["", f"Agreement: **{pct(s['agreement_rate'])}**."]
    if s["disagreements"]:
        items = []
        for d in s["disagreements"]:
            verdict = "pass" if d["dyno_pass"] else "fail"
            items.append(f"`{d['id']}` ({d['tier']}, stored {d['stored_score']}/5, Dyno {verdict})")
        lines += ["", "Disagreements: " + ", ".join(items)]
    return "\n".join(lines) + "\n"


def stored_picks(router: str, path: Path = PREDICTIONS) -> dict[str, str]:
    """The router's pick per prompt from the stored predictions (v3 is deterministic)."""
    picks = {}
    with path.open(encoding="utf-8") as f:
        for row in map(json.loads, f):
            if row["router"] == router:
                picks[row["id"]] = row["tier"]
    return picks


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="py -m gearbox.eval.dyno",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("cmd", choices=["cases", "run"])
    parser.add_argument("--n", type=int, default=30)
    parser.add_argument("--out", type=Path, default=Path("runs/dyno_cases.yaml"))
    parser.add_argument("--cap-gbp", type=float, default=DEFAULT_CAP_GBP)
    parser.add_argument("--yes", action="store_true", help="run: actually send (costs money)")
    args = parser.parse_args(argv)

    ids = sample_ids(DATA, args.n)
    cases = build_cases(DATA, ids)
    write_cases(cases, args.out)
    with_key = sum("expected" in c for c in cases)
    print(f"{len(cases)} cases ({with_key} with a gold answer) -> {args.out}")
    if args.cmd == "cases":
        return 0

    estimate = estimate_gbp(len(cases))
    print(f"estimate GBP {estimate:.2f} (cap {args.cap_gbp:.2f}); needs the API on port 8002")
    if estimate > args.cap_gbp:
        print("REFUSED: estimate is over the cap")
        return 1
    if not args.yes:
        print("dry run: add --yes to send it")
        return 0
    dyno_bin = Path(os.environ.get("DYNO_BIN", DEFAULT_DYNO_BIN))
    db_file = Path("runs/dyno.db")
    start = datetime.now(UTC)
    try:
        run_id = run_dyno(dyno_bin, args.out, db_file, args.cap_gbp)
        time.sleep(1)  # the last request-log row commits after the response
        report = dyno_report(dyno_bin, run_id, db_file)
    except DynoError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    rows = request_log_window(start, datetime.now(UTC))
    summary = summarise(report, ids, rows, DATA, stored_picks(get_config().routing.router))
    out = Path("reports/eval_dyno.md")
    out.write_text(render(summary), encoding="utf-8", newline="\n")
    Path("reports/eval_dyno.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    print(render(summary))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
